-- Merge under the same row lock used by Admin edits. Existing rules keep precedence.
WITH current_config AS (
    SELECT config FROM machine_navigation WHERE id = 1 FOR UPDATE
), type_mapping(legacy_id, machine_type, type_order) AS (
    VALUES (1, 'spin', 1), (2, 'treadmill', 2), (3, 'spin', 1), (5, 'rower', 5),
           (6, 'elliptical', 6), (16, 'stair', 16), (36, 'ski', 36)
), existing_rules AS (
    SELECT rule.value AS rule
    FROM current_config, jsonb_array_elements(config -> 'bleRules') AS rule
), existing_patterns AS (
    SELECT rule ->> 'machineType' AS machine_type, rule ->> 'match' AS match_type,
           lower(btrim(pattern.value) COLLATE "C") AS normalized
    FROM existing_rules, jsonb_array_elements_text(rule -> 'patterns') AS pattern
), candidates AS (
    SELECT source_row, machine_type, type_order, match_type, pattern,
           lower(btrim(pattern) COLLATE "C") AS normalized,
           CASE source_field WHEN 'ftmsble' THEN 'FTMS' ELSE 'PRIVATE' END AS protocol,
           CASE source_field WHEN 'ftmsble' THEN 0 ELSE char_length(btrim(pattern)) END AS specificity
    FROM legacy_machine_navigation_rules src
    JOIN type_mapping tm ON tm.legacy_id = src.legacy_machine_id
    WHERE source_field IN ('bluename', 'ftmsble')
), distinct_patterns AS (
    SELECT DISTINCT ON (machine_type, match_type, normalized) c.*
    FROM candidates c
    WHERE NOT EXISTS (
        SELECT 1 FROM existing_patterns e
        WHERE e.machine_type = c.machine_type AND e.match_type = c.match_type AND e.normalized = c.normalized
    )
    ORDER BY machine_type, match_type, normalized, source_row
), batches AS (
    SELECT *, (row_number() OVER (
        PARTITION BY machine_type, match_type, specificity ORDER BY source_row
    ) - 1) / 100 AS batch
    FROM distinct_patterns
), grouped_rules AS (
    SELECT machine_type, match_type, protocol, specificity, type_order, batch,
           jsonb_agg(pattern ORDER BY source_row) AS patterns
    FROM batches
    GROUP BY machine_type, match_type, protocol, specificity, type_order, batch
), additions AS (
    -- FTMS prefixes precede the legacy substring rules. A longer substring
    -- outranks a shorter one, with legacy machine order as the tie-break.
    SELECT *, row_number() OVER (
        ORDER BY (match_type = 'prefix') DESC, specificity DESC, type_order, batch
    ) + (SELECT coalesce(max((rule ->> 'priority')::integer), 0)
        FROM existing_rules WHERE (rule ->> 'enabled')::boolean) AS priority
    FROM grouped_rules
), new_rules AS (
    SELECT coalesce(jsonb_agg(jsonb_build_object(
        'id', gen_random_uuid(), 'machineType', machine_type, 'match', match_type,
        'patterns', patterns, 'preferredProtocol', protocol, 'priority', priority::integer, 'enabled', true
    ) ORDER BY priority), '[]'::jsonb) AS rules
    FROM additions
), new_resistance AS (
    SELECT coalesce(jsonb_agg(pattern ORDER BY source_row), '[]'::jsonb) AS patterns
    FROM legacy_machine_navigation_rules src
    WHERE src.source_field = 'DrapList' AND NOT EXISTS (
        SELECT 1 FROM current_config, jsonb_array_elements_text(config -> 'resistanceDisabledPatterns') AS current_pattern
        WHERE lower(btrim(current_pattern.value) COLLATE "C") = lower(btrim(src.pattern) COLLATE "C")
    )
)
UPDATE machine_navigation n
SET config = current_config.config || jsonb_build_object(
    'bleRules', (current_config.config -> 'bleRules') || new_rules.rules,
    'resistanceDisabledPatterns', (current_config.config -> 'resistanceDisabledPatterns') || new_resistance.patterns
)
FROM current_config, new_rules, new_resistance
WHERE n.id = 1;
